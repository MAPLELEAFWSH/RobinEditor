/**
 * 「按谁的约定画」—— 手绘贴图时的通道含义与默认档位。
 *
 * 来源分两类，界面上标清楚，别混：
 *   · **用户口述的流程**（他自己整理的做法）：通道含义 + 各通道默认填什么。
 *     那种教程原文、操作步骤、界面文案一个字都没搬进来 —— 只取了"哪个通道是什么、默认填几"这些事实，
 *     做法与界面都是本工程自己写的（见 `docs/来源与边界.md`）。
 *   · **本工程实测**：对着三个模型库的真产物量的那几套（`docs/产物配对实测.md`）。
 *
 * 为什么要这张表：通道含义**每种渲染约定都不一样**，而我们在 ⑤ 量出来的那套
 * （R 高光/反射、G 阴影基调、B 金属度、A Ramp 层）跟用户口述的那套
 * （R 金属、G AO、B 高亮、A 发光）**不是一回事**。用户在 ⑦ 里手绘时选错一套，
 * 整张图的通道就全错位了 —— 所以让他在画之前先选一次。
 */

export type 通道含义 = {
  /** 界面上显示的名字，比如"金属度" */
  name: string;
  /** 新块的默认档位（0-1） */
  def: number;
  /** 一句话：这个通道做什么用 */
  what: string;
};

export type 约定 = {
  id: string;
  name: string;
  /** 来源标注，界面上直接显示 */
  源: string;
  /** 这套约定的整体说明 */
  note: string;
  R: 通道含义;
  G: 通道含义;
  B: 通道含义;
  A: 通道含义;
  /** 画的时候要注意的几条（自己写的短笔记） */
  提示: string[];
};

