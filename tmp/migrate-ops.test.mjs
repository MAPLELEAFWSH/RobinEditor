/**
 * ⑥ 工程迁移打包的界面账（纯逻辑）测试。
 *
 * 管的是"表上那些数对不对、什么时候该拦住不让打包"。
 * 目标相对路径不在这里 —— 那条规则只有 Rust 里一份（界面拿干跑结果显示）。
 */
import { 汇总扫描, 分类问题 } from '../src/lib/modules/migrate/ops.ts';
/* 界面这一侧的那两个小工具（A1 那条拒绝的识别与转述）—— 它们也是纯函数，测得了 */
import { 是范围太大, 差错话 } from '../src/lib/io.ts';

let n = 0;
let bad = 0;
const ok = (c, m) => {
  n++;
  if (!c) {
    bad++;
    console.log(`  FAIL ${m}`);
  }
};
const eq = (a, b, m) => ok(a === b, `${m}（期望 ${b}，实得 ${a}）`);

/** 造一份扫描结果 */
function 造({ 对象 = [], 命中 = [], 在盘上 = [], 问题 = [], 贴图 = [], 特效 = [] } = {}) {
  return {
    pmm: 'P.pmm',
    emm: 'P.emm',
    objects: 对象,
    effects: 特效,
    在盘上,
    pmm_hits: 命中,
    问题,
    textures: 贴图
  };
}
const 对象条 = (i, kind = 'model') => ({ key: `Pmd${i}`, kind, index: i, path: `D:\\x\\${i}.pmx` });

/* ---------- 问题分类 ---------- */
{
  const 类 = 分类问题([
    '同名重复：Pmd1 的完整路径出现 2 处',
    '找不到文件名：Pmd2 的「a.pmx」一处都没有',
    '同名重复：Pmd3 的完整路径出现 3 处',
    '没有冒号的一句'
  ]);
  eq(类[0].类, '同名重复', '同类问题归到一起，多的在前');
  eq(类[0].数, 2, '同名重复 2 条');
  eq(类.find((x) => x.类 === '找不到文件名').数, 1, '找不到文件名 1 条');
  eq(类.find((x) => x.类 === '别的').数, 1, '没冒号的算「别的」，不丢');
  eq(分类问题([]).length, 0, '没有问题就是空表');
}

/* ---------- 汇总：命中率与两级命中 ---------- */
{
  const 汇 = 汇总扫描(
    造({
      对象: [对象条(1), 对象条(2), 对象条(3), 对象条(4)],
      命中: [
        { key: 'Pmd1', offset: 10, path: 'a', 怎么找到的: '完整路径' },
        { key: 'Pmd2', offset: 20, path: 'b', 怎么找到的: '完整路径' },
        { key: 'Pmd3', offset: 30, path: 'c', 怎么找到的: '只文件名' }
      ],
      在盘上: [true, true, true, false],
      贴图: [
        { pmx: 'a.pmx', index: 0, path: 't1.png', exists: true },
        { pmx: 'a.pmx', index: 1, path: 't2.png', exists: false }
      ],
      问题: ['同名重复：Pmd4 …']
    })
  );
  eq(汇.对象数, 4, '对象 4 条');
  eq(汇.命中数, 3, '命中 3 条');
  eq(汇.精确命中, 2, '完整路径 2 条');
  eq(汇.结构命中, 1, '放宽那三级 1 条');
  eq(汇.命中率, 75, '命中率 75%');
  eq(汇.缺文件数, 1, '盘上缺 1 个');
  eq(汇.贴图缺, 1, '贴图缺 1 条');
  eq(汇.可打包, false, '有对象没命中 → 拦住不让打包');
  ok(汇.拦.includes('没定位到'), `拦住的原因要说清是哪一条（${汇.拦}）`);
}

/* ---------- 全命中但命中率不到 90% 也要拦 ---------- */
{
  const 对象 = Array.from({ length: 20 }, (_, i) => 对象条(i + 1));
  const 命中 = 对象.slice(0, 17).map((o) => ({ key: o.key, offset: 0, path: o.path, 怎么找到的: '精确路径' }));
  const 汇 = 汇总扫描(造({ 对象, 命中, 在盘上: 对象.map(() => true) }));
  eq(汇.命中率, 85, '85%');
  eq(汇.可打包, false, '85% 也拦住（宁可拦错，不可改错）');
  ok(汇.拦.includes('没定位到') || 汇.拦.includes('85%'), `拦住的话要说清是哪种拦法（${汇.拦}）`);
}

/* ---------- 全命中且都在盘上 → 放行 ---------- */
{
  const 对象 = [对象条(1), 对象条(2)];
  const 命中 = 对象.map((o) => ({ key: o.key, offset: 5, path: o.path, 怎么找到的: '精确路径' }));
  const 汇 = 汇总扫描(造({ 对象, 命中, 在盘上: [true, true] }));
  eq(汇.可打包, true, '全命中 → 可以打包');
  eq(汇.拦, '', '放行时没有拦截理由');
  /* 盘上缺文件**不拦**：缺文件只报告，不影响"能改多少就改多少" */
  const 汇2 = 汇总扫描(造({ 对象, 命中, 在盘上: [true, false] }));
  eq(汇2.可打包, true, '缺文件不拦打包（缺的只报告）');
  eq(汇2.缺文件数, 1, '缺文件数照实算');
}

/* ---------- 空工程 ---------- */
{
  const 汇 = 汇总扫描(造({}));
  eq(汇.对象数, 0, '没有对象');
  eq(汇.命中率, 0, '没有对象时命中率是 0，不除零');
  eq(汇.可打包, false, '空工程不许打包');
  ok(汇.拦.includes('没有对象'), '说清是空工程');
}

/* ---------- A1：界面认不认"范围太大"那条拒绝 ----------
   后端（Rust）在这条上是唯一属主：超了层数/条目/时间就抛一句
   「范围太大，请给更具体的起点…」。界面要**原样显示**它，不能包成"检索失败：…"
   （包一层就看不出该怎么办了）。这一组钉的就是这两边那句话的对齐。 */
{
  const 真话 =
    '范围太大，请给更具体的起点：D:\\ 是**整个盘** —— 递归扫它要把盘里每一个目录都走一遍。换成更靠里的一个目录，或者把起点分成几个分别加。';
  ok(是范围太大(真话), '后端那句"范围太大"要被认出来');
  ok(是范围太大(new Error(真话)), '包成 Error 也要认（有的路径是 Error）');
  ok(!是范围太大('找不到文件：D:\\x.pmx'), '别的错误不许被当成范围太大');
  ok(!是范围太大(''), '空串不算');
  eq(差错话(真话), 真话, 'Tauri 拒绝时给的是字符串：要原样带出来，不能显示成 undefined');
  eq(差错话(new Error('炸了')), '炸了', 'Error 取 message');
  eq(差错话(null), 'null', '别的东西也要有个说法，不许 undefined');
  /* 界面上那条人话必须**带着后端原文**（用户按它知道该换什么起点） */
  const 界面说 = `${差错话(真话)}\n（起点可以加好几个…）`;
  ok(界面说.startsWith('范围太大，请给更具体的起点'), `界面要原样带出那句话（实得 ${界面说.slice(0, 20)}…）`);
}

console.log(`\nmigrate-ops：${n} 条断言，${bad} 条没过`);
process.exit(bad ? 1 : 0);
