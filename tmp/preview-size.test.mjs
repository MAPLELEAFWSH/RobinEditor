/**
 * `预览长边()` 的契约测试。
 *
 * 它管的是"预览该按多长的边生成"——原来各页硬编码 320 / 384 / 512，
 * 而预览台在 150% 缩放的 1600 档屏上约 940 CSS px 宽 = 1410 设备像素，
 * 512 被 CSS 拉上去就是放大，看着又糊又小（用户报的就是这个）。
 *
 * 这里钉三件事：跟着视口走、封顶、不低过下限。
 * 上限那两个数是 `tmp/preview-cost.mjs` 量出来的（1536 时调色一路 69.8ms 超一帧预算，所以调色页传 1024）。
 */
import { 预览长边 } from '../src/lib/img.ts';

let n = 0;
let bad = 0;
const ok = (c, m) => {
  n++;
  if (!c) {
    bad++;
    console.log(`  FAIL ${m}`);
  }
};
const eq = (a, b, m) => ok(a === b, `${m}（期望 ${b}，实得 ${a}）`);

/** 换一个"视口"来跑。函数是在调用时读 window 的，所以这样能测得到 */
function 在视口里(innerWidth, dpr, fn) {
  const 原 = globalThis.window;
  globalThis.window = { innerWidth, devicePixelRatio: dpr };
  try {
    return fn();
  } finally {
    globalThis.window = 原;
  }
}

/* 没有 window（构建期/预渲染）时给上限，不能崩 */
delete globalThis.window;
eq(预览长边(), 1536, '没有 window 时给默认上限');
eq(预览长边(1024), 1024, '没有 window 时按传进来的上限');

/* 用户那台机器：2560×1600 @150% → CSS 视口 1707 宽 */
eq(在视口里(1707, 1.5, () => 预览长边()), 1536, '用户的屏上封到 1536（不是 512）');
eq(在视口里(1707, 1.5, () => 预览长边(1024)), 1024, '调色那条路封到 1024');

/* 小窗口：跟着视口缩，但别低过下限 —— 太低就又回到"看不清"了 */
eq(在视口里(800, 1, () => 预览长边()), 576, '窄窗口跟着算（800×0.72=576）');
eq(在视口里(400, 1, () => 预览长边()), 512, '窗口很小时托底到下限 512');

/* 破坏性对照：这条函数不许变成"一个常数" */
ok(
  在视口里(800, 1, () => 预览长边()) !== 在视口里(1400, 1, () => 预览长边()),
  '不同视口给出的值不该一样（它必须真的跟着视口走）'
);

console.log(`\n通过 ${n} 条，失败 ${bad} 条`);
process.exit(bad ? 1 : 0);
