/**
 * ① 的**界面层守卫**：整段进出 / 名字顺手还原 / 别把账摆给用户看。
 *
 * 这份守 guarding 的要求前后换过一次口径，两次都是用户的原话：
 *   · 2026-09-23：「需要保证乱码可以翻译而不是给我丢回乱码，最起码要修复」——
 *     那时候的结论是"把够不着门槛的段连候选、增益、门槛一起摆出来，让人点「就用这个」"。
 *   · 2026-09-24（现在这条）：「**我复制进去的文本你就要还原一整段给我，别只会细说
 *     把什么还原成什么，把算过的几条路删除**」——上一版那个做法被明确否掉了：
 *     用户要的是**右边直接给出整段结果**，不是一张要人逐条认的候选表。
 *
 * 所以这份守卫现在钉的是**新的那一条**（旧的断言全部翻过来）：
 *   1. 粘贴那条路上，界面上必须有一块**画整段结果**的地方（不是只有一颗复制按钮）；
 *   2. 逐段的候选 / 增益 / 门槛 / 「就用这个」 **不许再出现在界面上**；
 *   3. 文件/目录名要**跟正文一趟做掉**（扫 + 改名 + 能回滚），不再单开一栏让人一条条认；
 *   4. 批量里"看着像乱码但没自动改的段"仍然要露头 + 有去处（这条没被否掉，继续钉）。
 *
 * 后端那半边（门槛、候选、强制应用）在 `src-tauri/src/textenc.rs` 的 cargo 测试里还钉着 ——
 * 界面上撤掉出口不等于后端那条能力要删。
 */
import fs from 'node:fs';

let n = 0;
let bad = 0;
const ok = (c, m) => {
  n++;
  if (!c) {
    bad++;
    console.log(`  FAIL ${m}`);
  }
};

const 读 = (p) => fs.readFileSync(p, 'utf8');
const 界面 = 读('src/lib/modules/glitch/Glitch.svelte');
const 注册表 = 读('src/lib/modules/registry.ts');

/* 「文本」栏那一段 = 从文件开头到 batch 分支之前。
   后面对"逐段的账"那几条只在这**一段**里判 —— 「名称」栏里还留着一颗「就用这个」，
   那是另一件事（用户要的是**粘贴那条路**别再细说）。 */
const 文本栏 = 界面.slice(0, 界面.indexOf("{:else if panelId === 'batch'}"));
ok(文本栏.length > 1000, '切得出「文本」栏那一段（找不到 batch 分支就是切法过期了，得改这份守卫）');

/* ---------- 1. 整段进、整段出 ---------- */
ok(/class="pair__out"[^>]*>\{还原过 \? 日文/.test(界面), '粘贴那条路要有一块画**整段结果**的地方（`pair__out` 里直接出 `日文`）');
ok(界面.includes('还原过'), '要有"跑过没有"这个状态（不然没跑之前右边会假出一个结果）');
ok(界面.includes('复制结果'), '要有一颗「复制结果」（整段拿走）');
ok(界面.includes('整段'), '界面上要说明这是整段的结果');

/* ---------- 2. 「文本」栏里逐段的账不许再摆出来（用户明确要求删掉） ----------
   判的是**渲染出来的形状**（`增益 {…}` 这种），不是注释里的字 ——
   注释里还要讲清"以前是什么样、为什么撤掉"。 */
ok(!/>\s*就用这个/.test(文本栏), '「文本」栏不许再出现「就用这个」按钮');
ok(!/function 用候选\(/.test(界面), '逐段挑候选的处理函数要删掉（不是留着不画）');
ok(!界面.includes('repairTextForced'), '界面不许再走 repair_text_forced 那条（出口已撤）');
ok(!/增益\s*\{|门槛\s*\{|假名上升\s*\{/.test(文本栏), '「文本」栏不许再渲染增益 / 门槛 / 假名上升');
ok(!文本栏.includes('it.s.候选'), '候选列表不许再渲染');
ok(!/打分\s*\{/.test(文本栏), '「打分 x → y」那行读数也不留');

/* ---------- 3. 名字跟正文一趟做掉 ---------- */
ok(界面.includes('scanNames'), '「文件」栏扫目录时要连名字一起扫（scanNames）');
ok(界面.includes('renameEntries'), '名字要真的改（renameEntries）');
ok(界面.includes('undoRenames') || 界面.includes('回滚'), '名字改完要能回滚');
ok(
  /filter\(\(h\) => h\.自动可改\)/.test(界面),
  '名字只许动"判据自己有把握的"那些（自动可改）—— 这是防"把好名字改成乱码"的那道闸'
);
ok(
  !/for \(const h of 名命中\) m\[h\.path\] = true;/.test(界面) || 界面.includes('连没把握的也勾上'),
  '要无脑全勾的话，按钮文案必须自己说清是"连没把握的也勾上"'
);

/* ---------- 4. 批量里"没自动改的段"仍然要露头 + 有去处 ---------- */
ok(界面.includes('h.uncertain'), '批量列表要渲染 uncertain（看着像乱码但没自动改的段）');
ok(界面.includes('去文本页挑'), '那些段要有个入口去挑（不能只列出来没去处）');

/* ---------- 5. 那一栏还在（这一轮没删；删了就把这条一起翻过来） ---------- */
ok(注册表.includes("id: 'names'") && 界面.includes("panelId === 'names'"), '「名字还原」分区暂时还在（注册表 + 组件分支成对）');

console.log(`\nglitch 界面守卫：通过 ${n} 条，失败 ${bad} 条`);
process.exit(bad ? 1 : 0);
